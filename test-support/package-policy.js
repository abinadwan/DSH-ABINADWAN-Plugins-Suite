const approved = new Set(approvedPackageFiles)
export function validatePackageFiles(files) {
  const actual = files.map(file=>file.path)
  if(actual.some(path=>typeof path!=='string'||!approved.has(path)))throw new Error('Development preview or tooling leaked into production package (unapproved file)')
  if(new Set(actual).size!==actual.length||actual.length!==approved.size||approvedPackageFiles.some(path=>!actual.includes(path)))throw new Error('Production package inventory is incomplete or duplicated')
}
