import test from 'node:test'
import assert from 'node:assert/strict'
import { clientHarness, tick, base, walk } from '../test-support/client.js'

test('Host Environment toggle removes its slots, timers and subscriptions, then restores once', async t => {
  const app = await clientHarness()
  t.after(() => app.dispose())
  assert.equal(app.tabs.records.size, 1)
  assert.ok(app.slot('sidebar.right.pane.tab'))
  assert.equal(app.timers.size, 1)
  assert.equal(app.mountedListeners.size, 1)
  app.setRows(app.rows().map(row => ({ ...row, enabled: row.moduleName !== `${base}/environment-context` })))
  await app.changed()
  assert.equal(app.tabs.records.size, 0)
  assert.equal(app.timers.size, 0)
  assert.equal(app.mountedListeners.size, 0)
  assert.equal(app.slot('sidebar.right.pane.tab'), undefined)
  assert.ok(app.slot('plugins.detail.section'), 'suite controls survive Environment disable')
  app.setRows(app.rows().map(row => ({ ...row, enabled: true, fiberPhase: 'active' })))
  await app.changed()
  await app.changed()
  assert.equal(app.tabs.records.size, 1)
  assert.equal(app.timers.size, 1)
})

test('failed and out-of-order inventory reads cannot keep or resurrect a disabled Environment', async t => {
  const app = await clientHarness()
  t.after(() => app.dispose())
  let resolveOld
  const old = new Promise(resolve => { resolveOld = resolve })
  const active = app.rows()
  app.inventory(() => old)
  await app.changed()
  app.inventory(async () => [])
  await app.changed()
  assert.equal(app.tabs.records.size, 0)
  resolveOld(active)
  await tick()
  assert.equal(app.tabs.records.size, 0)
  app.inventory(async () => { throw new Error('offline') })
  await app.changed()
  assert.equal(app.tabs.records.size, 0)
  app.inventory(async () => active)
  app.ctx.emit('connection/reset')
  await tick()
  assert.equal(app.tabs.records.size, 1)
})

test('access withdrawal and suite disposal prevent late mounts and release all resources', async () => {
  const app = await clientHarness()
  let resolvePending
  app.inventory(() => new Promise(resolve => { resolvePending = resolve }))
  await app.changed()
  app.access.set(false)
  resolvePending(app.rows())
  await tick()
  assert.equal(app.tabs.records.size, 0)
  assert.equal(app.events.size, 0)
  app.inventory(async () => app.rows())
  app.access.set(true)
  await tick()
  assert.equal(app.tabs.records.size, 1)
  await app.dispose()
  assert.equal(app.tabs.records.size, 0)
  assert.equal(app.slots.records.size, 0)
  assert.equal(app.events.size, 0)
  assert.equal(app.timers.size, 0)
  assert.equal(app.mountedListeners.size, 0)
})

test('Profile component renders an honest read-only draft, with no data-entry or save controls', async t => {
  const app = await clientHarness()
  t.after(() => app.dispose())
  assert.equal([...app.slots.records.values()].some(x => x.options.id === 'abinadwan-profile-draft'), false)
  app.setRows(app.rows().map(row => ({ ...row, enabled: true, fiberPhase: 'active' })))
  await app.changed()
  const draft = app.slots.records.get('abinadwan-profile-draft')?.component
  assert.equal(typeof draft, 'function')
  assert.equal(draft({ subject: { kind: 'bundle', pkg: { name: 'other' } } }), null)
  const node = draft({ subject: { kind: 'bundle', pkg: { name: base } } })
  const tree = node.type(node.props)
  assert.ok(walk(tree, x => x.props?.['data-personal-profile-draft'] === ''))
  assert.equal(walk(tree, x => ['input', 'textarea', 'select', 'form'].includes(x.type)), null)
  const text = JSON.stringify(tree)
  for (const label of ['Name', 'Date of birth', 'Nationality', 'Gender', 'Custom agent instructions',
    'Allow the agent to use approved profile information', 'Off', 'Empty']) assert.ok(text.includes(label), label)
  app.setRows([])
  await app.changed()
  assert.equal(app.slots.records.has('abinadwan-profile-draft'), false)
})

test('rapid access off/on and failed Host phases never duplicate the Environment UI', async t => {
  const app = await clientHarness()
  t.after(() => app.dispose())
  app.access.set(false)
  app.access.set(true)
  await tick()
  assert.equal(app.tabs.records.size, 1)
  assert.equal(app.mountedListeners.size, 1)
  app.setRows(app.rows().map(row => ({ ...row, fiberPhase: 'failed' })))
  await app.changed()
  assert.equal(app.tabs.records.size, 0)
  app.inventory(async () => ({ invalid: 'inventory' }))
  await app.changed()
  assert.equal(app.tabs.records.size, 0)
})

test('a response arriving after suite disposal cannot remount Component UI', async () => {
  const app = await clientHarness()
  let resolvePending
  const rows = app.rows()
  app.inventory(() => new Promise(resolve => { resolvePending = resolve }))
  await app.changed()
  await app.dispose()
  resolvePending(rows)
  await tick()
  assert.equal(app.tabs.records.size, 0)
  assert.equal(app.slots.records.size, 0)
})
