import { readFile, writeFile } from 'node:fs/promises'
import { Script } from 'node:vm'

const root = new URL('../', import.meta.url)
const read = async path => (await readFile(new URL(path, root), 'utf8')).replace(/\r\n/g, '\n')
const fragment = name => read('client-src/' + name + '.js.inc')
const order = ["preamble","@arabic","shared","update","environment","profile-header","@preferences","profile","shared-settings","catalog","archive","reasoning","direct-chat","registrations","entry"]
const dictionary = JSON.parse(await read('locale/dsh-ui-ar.json'))
const preferences = await read('plugins/personal-profile/preferences.js')
const first = preferences.indexOf('const PROFILE_STYLES')
const last = preferences.indexOf('export const RECORD_VERSION')
if (first < 0 || last <= first) throw new Error('Missing canonical profile renderer')
const profile = preferences.slice(first, last).replaceAll('export function ', 'function ').trimEnd()
  .split('\n').map(line => line ? '    ' + line : '').join('\n') + '\n'
const blocks = await Promise.all(order.map(name =>
  name === '@arabic' ? '    const ARABIC_UI_DICTIONARIES = ' + JSON.stringify(dictionary) + '\n'
    : name === '@preferences' ? profile : fragment(name)))
const output = "// Generated by npm run build:client. Edit client-src and canonical data, not this file.\n" + blocks.join('')
new Script(output, { filename: 'client.js' })
const target = new URL('client.js', root)
if (process.argv.length > 3 || process.argv[2] && process.argv[2] !== '--check') {
  throw new Error('Usage: node scripts/build-client.mjs [--check]')
}
if (process.argv[2] === '--check') {
  if (await read('client.js') !== output) throw new Error('client.js is stale; run npm run build:client')
  console.log('Verified deterministic DSH browser carrier.')
} else {
  await writeFile(target, output)
  console.log('Generated DSH browser carrier.')
}
